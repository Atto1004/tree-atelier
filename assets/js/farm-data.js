/* ---------- 흉고(B) 원문 해석 ----------
   '17'          단간, 흉고 17cm
   '24(19+11)'   다간 — 환산값 24, 각 줄기 19·11
   '15+12'       다간 — 각 줄기만 기록 (환산값 미기재)          */
function parseBRaw(raw) {
  if (raw == null) return { main: null, stems: null, uncertain: false };
  const s = String(raw);
  const uncertain = s.includes('?');
  let m = /^(\d+(?:\.\d+)?)\(([\d+.]+)\)/.exec(s);
  if (m) return { main: +m[1], stems: m[2].split('+').map(Number), uncertain };
  m = /^(\d+(?:\.\d+)?(?:\+\d+(?:\.\d+)?)+)/.exec(s);
  if (m) return { main: null, stems: m[1].split('+').map(Number), uncertain };
  m = /^(\d+(?:\.\d+)?)/.exec(s);
  return { main: m ? +m[1] : null, stems: null, uncertain };
}

const FARM_TREES = FARM_ROWS.map((row, i) => {
  const [code, r, bRaw, dose, note] = row;
  const cm = /^([A-D])-(H|\d+)-(\d+)$/.exec(code);
  const b = parseBRaw(bRaw);
  return {
    no: i + 1,
    code,
    zone: cm[1],
    line: cm[2],           /* 열 (H = 하우스/별도열로 추정) */
    seq: +cm[3],
    r,
    bRaw: bRaw,
    b: b.main,
    stems: b.stems,        /* 다간이면 줄기별 흉고 */
    multi: !!(b.stems && b.stems.length > 1),
    dose: dose == null ? null : dose,
    note: note || null,
  };
});

/* ---------- 조회 ---------- */
const FARM_CODE_RE = /^([A-D])\s*-?\s*(H|\d{1,2})\s*-\s*(\d{1,2})$/i;

function registryByCode(input) {
  const m = FARM_CODE_RE.exec(String(input || '').trim().toUpperCase());
  if (!m) return null;
  const code = `${m[1]}-${m[2]}-${+m[3]}`;
  return FARM_TREES.find(t => t.code === code) || null;
}

function registryZone(zoneId) {
  return FARM_TREES.filter(t => t.zone === zoneId);
}

function registryStats(trees) {
  const list = trees || FARM_TREES;
  const rs = list.map(t => t.r).filter(Boolean);
  return {
    count: list.length,
    rMin: Math.min(...rs),
    rMax: Math.max(...rs),
    rAvg: Math.round(rs.reduce((a, b) => a + b, 0) / rs.length),
    multi: list.filter(t => t.multi).length,
    bansong: list.filter(t => t.note === '반송').length,
  };
}
